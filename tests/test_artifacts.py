"""The dependency manifest, and the JCL join that closes its ddnames."""

import importlib.util
import json
import sys
from pathlib import Path

from eztrieve_dependencies.parser import parse_eztrieve
from eztrieve_dependencies.views import (bind_jcl_ddnames, build_eztrieve_artifacts,
                                         jcl_steps_running)

EXAMPLES = Path(__file__).resolve().parents[1] / "examples"
FIXTURES = Path(__file__).resolve().parent / "fixtures"
MACROS = {p.stem.upper(): p.read_text(encoding="utf-8")
          for p in EXAMPLES.glob("*.mac")}


def _artifacts(name: str, resolver=None):
    program = parse_eztrieve((EXAMPLES / name).read_text(encoding="utf-8"),
                             resolver=resolver, source_name=name)
    return build_eztrieve_artifacts(program)


def _by_name(manifest):
    return {a["artifact"]: a for a in manifest["artifacts"]}


def _payroll_jcl_lineage():
    """A committed jcl-dependencies LINEAGE view, as a FIXTURE rather than one built live.

    This package must not depend on the JCL one - they are peers - so the JCL model arrives
    as data, which is what it actually is: a schema contract between two distributions that
    release separately. Regenerated by tools/refresh_fixture.py, which fails loudly if the
    shape has drifted, so the two learn about a schema change from a red test rather than
    from a quietly unbound manifest.
    """
    return json.loads((FIXTURES / "payroll.jcl.lineage.json").read_text(encoding="utf-8"))


