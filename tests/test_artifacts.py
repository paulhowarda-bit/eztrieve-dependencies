def test_the_committed_jcl_fixture_still_has_the_shape_the_binder_reads():
    """The cross-repository contract, checked here so drift is a RED TEST rather than a
    quietly unbound manifest - which looks exactly like a manifest nobody tried to bind."""
    spec = importlib.util.spec_from_file_location(
        "refresh_fixture", Path(__file__).resolve().parents[1] / "tools"
        / "refresh_fixture.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["refresh_fixture"] = module
    spec.loader.exec_module(module)
    assert module.check() == []


def test_the_step_is_found_by_its_sysin_member_not_by_its_exec_pgm():
    """Both steps run EZTPA00 - the Easytrieve interpreter - so the step's program name
    cannot say which Easytrieve program runs. The SYSIN member can, and does."""
    lineage = _payroll_jcl_lineage()
    assert jcl_steps_running("PAYROLL", lineage) == ["RUNPAY"]
    assert jcl_steps_running("AUDITRPT", lineage) == ["RUNAUD"]
    assert jcl_steps_running("NOSUCH", lineage) == []


def test_binding_closes_the_ddname_to_dataset_chain():
    out = bind_jcl_ddnames(_artifacts("payroll.ezt"), _payroll_jcl_lineage())
    assert out["jclBinding"]["steps"] == ["RUNPAY"]
    assert out["jclBinding"]["boundFiles"] == 2
    row = _by_name(out)["PERSNL"]
    assert row["dataset"] == "PROD.HR.PERSNL.MASTER"
    assert row["identity"] == "global"
    assert row["resolvedBy"] == "JCL DD statement: PAYRUN.RUNPAY"
    assert "needs" not in row                      # the identity chain is closed
    assert row["boundBy"][0]["step"] == "RUNPAY"


def test_binding_carries_a_gdg_generation_across():
    out = bind_jcl_ddnames(_artifacts("payroll.ezt"), _payroll_jcl_lineage())
    assert _by_name(out)["PAYEXT"]["boundBy"][0]["generation"] == "+1"


def test_binding_to_the_wrong_step_is_what_naming_the_step_prevents():
    """RUNAUD reads a different dataset through the SAME ddname. Bound from that step, the
    answer would be confidently wrong - which is why the step is identified, not assumed."""
    out = bind_jcl_ddnames(_artifacts("payroll.ezt"), _payroll_jcl_lineage(),
                           steps=["RUNAUD"])
    assert _by_name(out)["PERSNL"]["dataset"] == "TEST.HR.PERSNL.SAMPLE"


def test_conflicting_bindings_list_candidates_and_flag_never_collapse():
    """The same ddname bound to different datasets across the supplied steps is a FACT -
    the program runs against different data in different steps - and picking one silently
    would be a lie."""
    out = bind_jcl_ddnames(_artifacts("payroll.ezt"), _payroll_jcl_lineage(),
                           steps=["RUNPAY", "RUNAUD"])
    row = _by_name(out)["PERSNL"]
    assert "dataset" not in row
    assert row["datasetCandidates"] == ["PROD.HR.PERSNL.MASTER", "TEST.HR.PERSNL.SAMPLE"]
    assert len(row["boundBy"]) == 2
    assert any("2 different datasets" in f for f in out["flags"])


def test_an_unidentifiable_step_binds_on_ddname_alone_and_says_so():
    out = bind_jcl_ddnames(_artifacts("custupd.ezt"), _payroll_jcl_lineage())
    assert out["jclBinding"]["steps"] == []
    assert "ddname alone" in out["jclBinding"]["basis"]
    assert any("bound from the wrong step" in f for f in out["flags"])


def test_a_compiled_program_execed_by_name_is_matched_directly():
    lineage = {"format": "jcl-dependencies-lineage", "job": "J", "source": "j.jcl",
               "steps": [], "ddBindings": [
                   {"program": "PAYROLL", "step": "S1", "ddname": "PERSNL",
                    "dataset": "PROD.HR.PERSNL.MASTER", "io": "input"}]}
    out = bind_jcl_ddnames(_artifacts("payroll.ezt"), lineage)
    assert "compiled load module" in out["jclBinding"]["basis"]
    assert _by_name(out)["PERSNL"]["dataset"] == "PROD.HR.PERSNL.MASTER"


def test_binding_does_not_mutate_the_input_manifest():
    manifest = _artifacts("payroll.ezt")
    bind_jcl_ddnames(manifest, _payroll_jcl_lineage())
    row = _by_name(manifest)["PERSNL"]
    assert "dataset" not in row and "needs" in row


def test_an_unmatched_ddname_is_left_honestly_unresolved():
    out = bind_jcl_ddnames(_artifacts("custupd.ezt"), _payroll_jcl_lineage(),
                           steps=["RUNPAY"])
    row = _by_name(out)["CUSTMAST"]
    assert "dataset" not in row and "needs" in row


