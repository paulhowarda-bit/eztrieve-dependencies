def test_a_file_row_is_a_ddname_and_says_it_still_needs_the_jcl():
    """Easytrieve names only the ddname. Reporting it as though it were a dataset identity
    would be the one lie this whole family of tools exists to avoid."""
    row = _by_name(_artifacts("payroll.ezt"))["PERSNL"]
    assert row["kind"] == "file" and row["dependency"] == "runtime"
    assert row["ddname"] == "PERSNL" and row["io"] == "read"
    assert row["identity"] == "program-local"
    assert row["resolvedBy"] == "JCL DD statement"
    assert "the DSN is not knowable from this source alone" in row["needs"]
    assert row["fields"] == 5 and row["recordLength"] == 150


def test_a_file_row_records_which_activities_touched_it_and_how():
    row = _by_name(_artifacts("custupd.ezt"))["CUSTMAST"]
    assert row["io"] == "read-write"
    hows = {(t["how"], t.get("operation")) for t in row["touchedBy"]}
    assert ("POINT", None) in hows and ("GET", None) in hows
    assert ("WRITE", "UPDATE") in hows


def test_a_macro_is_a_compile_time_artifact_and_an_unresolved_one_says_the_model_is_short():
    blind = _by_name(_artifacts("macroed.ezt"))
    assert blind["CUSTREC"]["kind"] == "macro"
    assert blind["CUSTREC"]["dependency"] == "compile-time"
    assert blind["CUSTREC"]["status"] == "unresolved"
    assert blind["CUSTREC"]["usedAt"][0]["arguments"] == ["1"]

    seeing = _by_name(_artifacts("macroed.ezt", resolver=MACROS.get))
    assert seeing["CUSTREC"]["status"] == "expanded"


def test_called_programs_and_file_exits_are_program_rows_with_their_role():
    art = _by_name(_artifacts("custupd.ezt"))
    assert art["AUDITLOG"]["kind"] == "program" and art["AUDITLOG"]["role"] == "called"
    assert art["TRANEDIT"]["role"] == "file exit"
    assert art["TRANEDIT"]["exitFor"] == ["TRANS"]
    assert "can change any field of TRANS" in art["TRANEDIT"]["needs"]


def test_reports_virtual_files_and_instream_tables_are_excluded_with_the_reason():
    excluded = {e["name"]: e for e in _artifacts("custupd.ezt")["excluded"]}
    assert excluded["CODETAB"]["kind"] == "instream-table"
    assert "in this source member" in excluded["CODETAB"]["reason"]

    excluded = {e["name"]: e for e in _artifacts("payroll.ezt")["excluded"]}
    assert excluded["PAYRPT"]["kind"] == "report"
    assert "goes to the run's SYSPRINT" in excluded["PAYRPT"]["reason"]

    program = parse_eztrieve("FILE W VIRTUAL\n  A 1 5 N\n", source_name="f.ezt")
    excluded = {e["name"]: e for e in build_eztrieve_artifacts(program)["excluded"]}
    assert excluded["W"]["kind"] == "virtual-file"


def test_an_sql_statement_contributes_its_tables_but_not_its_columns():
    program = parse_eztrieve(
        "DEFINE WS-ACCT W 8 A\n"
        "JOB INPUT NULL\n"
        "  SQL SELECT ACCT_NO INTO :WS-ACCT FROM GLDB.TRANSACTIONS\n",
        source_name="f.ezt")
    manifest = build_eztrieve_artifacts(program)
    row = _by_name(manifest)["GLDB.TRANSACTIONS"]
    assert row["kind"] == "db2-table" and row["dependency"] == "runtime"
    assert "not which columns it touches" in row["needs"]
    assert any("COLUMN-to-host-field mapping" in f for f in manifest["flags"])


def test_the_manifest_is_ordered_deterministically():
    order = [(a["kind"], a["artifact"]) for a in _artifacts("custupd.ezt")["artifacts"]]
    assert order == sorted(order, key=lambda r: ({"file": 0, "db2-table": 1, "program": 2,
                                                  "macro": 3}[r[0]], r[1]))


